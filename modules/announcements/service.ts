import { prisma } from "@/lib/db";
import type { Prisma } from "@/generated/prisma/client";
import type { Audience } from "@/generated/prisma/enums";
import type { AuthUser } from "@/lib/auth/types";
import { assertPermission, assertSchoolAccess, hasPermission, isAdmin, resolveSchoolId } from "@/lib/permissions";
import { AppError } from "@/lib/utils/errors";
import { audit } from "@/lib/audit";
import { notifyMany } from "@/lib/notifications";
import type { CreateAnnouncementInput, ListAnnouncementsInput, UpdateAnnouncementInput } from "./schema";

/** Upper bound on in-app notifications generated by one announcement. */
export const MAX_ANNOUNCEMENT_RECIPIENTS = 2000;

const include = {
  author: { select: { id: true, name: true, role: true } },
  _count: { select: { reads: true } },
} satisfies Prisma.AnnouncementInclude;

type AnnouncementRow = Prisma.AnnouncementGetPayload<{ include: typeof include }>;

function present(a: AnnouncementRow, readIds: Set<string>, manager: boolean) {
  const { _count, ...rest } = a;
  return { ...rest, read: readIds.has(a.id), readCount: manager ? _count.reads : undefined };
}

/** Validates audience/target against the school and the caller's scope (department heads: own department or any class). */
async function assertTarget(user: AuthUser, schoolId: string, audience: Audience, targetId: string | null | undefined) {
  if (audience === "DEPARTMENT") {
    if (!targetId) throw AppError.validation("targetId (departmentId) is required for DEPARTMENT audience");
    const dept = await prisma.department.findUnique({ where: { id: targetId }, select: { id: true, schoolId: true } });
    if (!dept || dept.schoolId !== schoolId) throw AppError.validation("Department must belong to the same school");
    if (user.role === "DEPARTMENT_HEAD" && user.departmentId !== targetId) throw AppError.forbidden("Department heads can only announce to their own department");
    return targetId;
  }
  if (audience === "CLASS") {
    if (!targetId) throw AppError.validation("targetId (classId) is required for CLASS audience");
    const cls = await prisma.schoolClass.findUnique({ where: { id: targetId }, select: { id: true, schoolId: true } });
    if (!cls || cls.schoolId !== schoolId) throw AppError.validation("Class must belong to the same school");
    return targetId;
  }
  if (user.role === "DEPARTMENT_HEAD") throw AppError.forbidden("Department heads can only announce to their own department or to classes");
  return null;
}

/** Resolves the user ids that an announcement targets (used for notifications and read statistics). */
export async function resolveAnnouncementRecipients(schoolId: string, audience: Audience, targetId: string | null): Promise<string[]> {
  const active = { schoolId, isActive: true } as const;
  const ids = async (where: Prisma.UserWhereInput) => (await prisma.user.findMany({ where: { ...active, ...where }, select: { id: true }, take: MAX_ANNOUNCEMENT_RECIPIENTS })).map((u) => u.id);
  switch (audience) {
    case "SCHOOL":
      return ids({});
    case "TEACHERS":
      return ids({ role: { in: ["TEACHER", "DEPARTMENT_HEAD", "SCHOOL_ADMIN", "PRINCIPAL"] } });
    case "STAFF":
      return ids({ role: "STAFF" });
    case "STUDENTS":
      return ids({ role: "STUDENT" });
    case "PARENTS":
      return ids({ role: "PARENT" });
    case "DEPARTMENT": {
      if (!targetId) return [];
      return ids({ OR: [{ teacher: { departmentId: targetId } }, { staff: { departmentId: targetId } }] });
    }
    case "CLASS": {
      if (!targetId) return [];
      return ids({
        OR: [
          { student: { classId: targetId } },
          { guardian: { students: { some: { student: { classId: targetId } } } } },
          { teacher: { OR: [{ courses: { some: { classId: targetId } } }, { homeroomClasses: { some: { id: targetId } } }] } },
        ],
      });
    }
  }
}

/** Prisma clause restricting announcements to what the caller's role may see. */
async function visibilityWhere(user: AuthUser): Promise<Prisma.AnnouncementWhereInput> {
  if (isAdmin(user)) return {};
  const or: Prisma.AnnouncementWhereInput[] = [{ audience: "SCHOOL" }, { authorUserId: user.id }];
  switch (user.role) {
    case "TEACHER":
    case "DEPARTMENT_HEAD": {
      or.push({ audience: "TEACHERS" }, { audience: "STUDENTS" }, { audience: "PARENTS" });
      if (user.departmentId) or.push({ audience: "DEPARTMENT", targetId: user.departmentId });
      if (user.teacherId) {
        const [courses, homerooms] = await Promise.all([
          prisma.course.findMany({ where: { teacherId: user.teacherId }, select: { classId: true }, distinct: ["classId"] }),
          prisma.schoolClass.findMany({ where: { homeroomTeacherId: user.teacherId }, select: { id: true } }),
        ]);
        const classIds = [...new Set([...courses.map((c) => c.classId), ...homerooms.map((h) => h.id)])];
        if (classIds.length) or.push({ audience: "CLASS", targetId: { in: classIds } });
      }
      break;
    }
    case "STAFF": {
      or.push({ audience: "STAFF" });
      const staff = user.staffId ? await prisma.staff.findUnique({ where: { id: user.staffId }, select: { departmentId: true } }) : null;
      const deptId = staff?.departmentId ?? user.departmentId;
      if (deptId) or.push({ audience: "DEPARTMENT", targetId: deptId });
      break;
    }
    case "STUDENT": {
      or.push({ audience: "STUDENTS" });
      const student = user.studentId ? await prisma.student.findUnique({ where: { id: user.studentId }, select: { classId: true } }) : null;
      if (student?.classId) or.push({ audience: "CLASS", targetId: student.classId });
      break;
    }
    case "PARENT": {
      or.push({ audience: "PARENTS" });
      if (user.guardianId) {
        const links = await prisma.studentGuardian.findMany({ where: { guardianId: user.guardianId }, select: { student: { select: { classId: true } } } });
        const classIds = [...new Set(links.map((l) => l.student.classId).filter((c): c is string => !!c))];
        if (classIds.length) or.push({ audience: "CLASS", targetId: { in: classIds } });
      }
      break;
    }
  }
  return { OR: or };
}

function activeWhere(now: Date): Prisma.AnnouncementWhereInput {
  return { publishAt: { lte: now }, OR: [{ expiresAt: null }, { expiresAt: { gt: now } }] };
}

async function readIdsFor(userId: string, announcementIds: string[]) {
  if (announcementIds.length === 0) return new Set<string>();
  const reads = await prisma.announcementRead.findMany({ where: { userId, announcementId: { in: announcementIds } }, select: { announcementId: true } });
  return new Set(reads.map((r) => r.announcementId));
}

export async function createAnnouncement(user: AuthUser, input: CreateAnnouncementInput) {
  assertPermission(user, "announcements:manage");
  const schoolId = resolveSchoolId(user);
  const targetId = await assertTarget(user, schoolId, input.audience, input.targetId);
  const publishAt = input.publishAt ?? new Date();
  if (input.expiresAt && input.expiresAt <= publishAt) throw AppError.validation("expiresAt must be after publishAt");
  const announcement = await prisma.announcement.create({
    data: { schoolId, title: input.title, body: input.body, authorUserId: user.id, audience: input.audience, targetId, priority: input.priority, publishAt, expiresAt: input.expiresAt ?? null, attachments: input.attachments },
    include,
  });
  await audit({ user, schoolId, action: "announcement.create", entityType: "Announcement", entityId: announcement.id, after: announcement });
  if (publishAt <= new Date()) await notifyRecipients(announcement);
  return present(announcement, new Set(), true);
}

async function notifyRecipients(a: { id: string; schoolId: string; title: string; audience: Audience; targetId: string | null; authorUserId: string; priority: string }) {
  const recipients = (await resolveAnnouncementRecipients(a.schoolId, a.audience, a.targetId)).filter((id) => id !== a.authorUserId).slice(0, MAX_ANNOUNCEMENT_RECIPIENTS);
  await notifyMany(recipients, { schoolId: a.schoolId, type: "ANNOUNCEMENT", title: `${a.priority === "URGENT" ? "[URGENT] " : ""}${a.title}`, link: `/announcements/${a.id}` });
  return recipients.length;
}

/** Announcements visible to the caller, each with `read` for the caller (and `readCount` for managers). */
export async function listAnnouncementsForUser(user: AuthUser, input: ListAnnouncementsInput = {}) {
  assertPermission(user, "announcements:read");
  const schoolId = resolveSchoolId(user);
  const manager = hasPermission(user, "announcements:manage");
  const now = new Date();
  const and: Prisma.AnnouncementWhereInput[] = [await visibilityWhere(user)];
  if (!manager || input.includeInactive === "false") and.push(activeWhere(now));
  const where: Prisma.AnnouncementWhereInput = { schoolId, audience: input.audience, AND: and };
  if (input.unreadOnly === "true") where.reads = { none: { userId: user.id } };
  const items = await prisma.announcement.findMany({ where, include, orderBy: [{ priority: "desc" }, { publishAt: "desc" }], take: 200 });
  const readIds = await readIdsFor(user.id, items.map((a) => a.id));
  return items.map((a) => present(a, readIds, manager));
}

export async function getAnnouncement(user: AuthUser, id: string) {
  assertPermission(user, "announcements:read");
  const announcement = await prisma.announcement.findUnique({ where: { id }, include });
  if (!announcement) throw AppError.notFound("Announcement");
  assertSchoolAccess(user, announcement.schoolId);
  const manager = hasPermission(user, "announcements:manage");
  const and: Prisma.AnnouncementWhereInput[] = [await visibilityWhere(user)];
  if (!manager) and.push(activeWhere(new Date()));
  const visible = await prisma.announcement.findFirst({ where: { id, AND: and }, select: { id: true } });
  if (!visible) throw AppError.notFound("Announcement");
  const readIds = await readIdsFor(user.id, [id]);
  return present(announcement, readIds, manager);
}

export async function markAnnouncementRead(user: AuthUser, id: string) {
  await getAnnouncement(user, id);
  // Idempotent under concurrency (a page can fire this twice): insert-or-ignore, then read back.
  await prisma.announcementRead.createMany({ data: [{ announcementId: id, userId: user.id }], skipDuplicates: true });
  const read = await prisma.announcementRead.findUniqueOrThrow({ where: { announcementId_userId: { announcementId: id, userId: user.id } } });
  return { announcementId: id, read: true, readAt: read.readAt };
}

/** Read statistics for managers: who has read the announcement and how many recipients it targets. */
export async function announcementReadStats(user: AuthUser, id: string) {
  assertPermission(user, "announcements:manage");
  const announcement = await prisma.announcement.findUnique({ where: { id } });
  if (!announcement) throw AppError.notFound("Announcement");
  assertSchoolAccess(user, announcement.schoolId);
  if (user.role === "DEPARTMENT_HEAD" && announcement.authorUserId !== user.id) throw AppError.forbidden();
  const [reads, recipients] = await Promise.all([
    prisma.announcementRead.findMany({ where: { announcementId: id }, include: { user: { select: { id: true, name: true, role: true } } }, orderBy: { readAt: "desc" } }),
    resolveAnnouncementRecipients(announcement.schoolId, announcement.audience, announcement.targetId),
  ]);
  const recipientCount = recipients.filter((r) => r !== announcement.authorUserId).length;
  return {
    announcementId: id,
    readCount: reads.length,
    recipientCount,
    readRate: recipientCount ? Math.round((reads.length / recipientCount) * 1000) / 10 : null,
    readers: reads.map((r) => ({ userId: r.userId, name: r.user.name, role: r.user.role, readAt: r.readAt })),
  };
}

function assertCanEdit(user: AuthUser, announcement: { authorUserId: string }) {
  if (isAdmin(user) || announcement.authorUserId === user.id) return;
  throw AppError.forbidden("Only the author or an administrator can modify this announcement");
}

export async function updateAnnouncement(user: AuthUser, id: string, input: UpdateAnnouncementInput) {
  assertPermission(user, "announcements:manage");
  const before = await prisma.announcement.findUnique({ where: { id }, include });
  if (!before) throw AppError.notFound("Announcement");
  assertSchoolAccess(user, before.schoolId);
  assertCanEdit(user, before);
  const audience = input.audience ?? before.audience;
  const targetId = input.audience !== undefined || input.targetId !== undefined ? await assertTarget(user, before.schoolId, audience, input.targetId ?? before.targetId) : undefined;
  const publishAt = input.publishAt ?? before.publishAt;
  const expiresAt = input.expiresAt === undefined ? before.expiresAt : input.expiresAt;
  if (expiresAt && expiresAt <= publishAt) throw AppError.validation("expiresAt must be after publishAt");
  const announcement = await prisma.announcement.update({
    where: { id },
    data: { title: input.title, body: input.body, audience: input.audience, targetId, priority: input.priority, publishAt: input.publishAt, expiresAt: input.expiresAt, attachments: input.attachments },
    include,
  });
  await audit({ user, schoolId: before.schoolId, action: "announcement.update", entityType: "Announcement", entityId: id, before, after: announcement });
  // Publishing a previously scheduled announcement now → notify.
  const now = new Date();
  if (before.publishAt > now && announcement.publishAt <= now) await notifyRecipients(announcement);
  const readIds = await readIdsFor(user.id, [id]);
  return present(announcement, readIds, true);
}

export async function deleteAnnouncement(user: AuthUser, id: string) {
  assertPermission(user, "announcements:manage");
  const before = await prisma.announcement.findUnique({ where: { id } });
  if (!before) throw AppError.notFound("Announcement");
  assertSchoolAccess(user, before.schoolId);
  assertCanEdit(user, before);
  await prisma.announcement.delete({ where: { id } });
  await audit({ user, schoolId: before.schoolId, action: "announcement.delete", entityType: "Announcement", entityId: id, before });
}

/** Dashboard helper (no permission check beyond role scoping): latest active announcements for the user. */
export async function recentAnnouncementsForUser(user: AuthUser, take = 5) {
  const schoolId = resolveSchoolId(user);
  const where: Prisma.AnnouncementWhereInput = { schoolId, AND: [await visibilityWhere(user), activeWhere(new Date())] };
  const items = await prisma.announcement.findMany({ where, include, orderBy: [{ priority: "desc" }, { publishAt: "desc" }], take });
  const readIds = await readIdsFor(user.id, items.map((a) => a.id));
  return items.map((a) => present(a, readIds, false));
}
